export function t(locale: string): Dict {
  return locale === "en" ? en : ru;
}

export function tf(template: string, vars: Record<string, string>): string {
  return Object.entries(vars).reduce((acc, [k, v]) => acc.replaceAll(`{${k}}`, v), template);
}
